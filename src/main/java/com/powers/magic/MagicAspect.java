package com.powers.magic;

/**
 * Semantic forces used to resolve interactions independently from individual
 * ability implementations. An action may carry several aspects in priority
 * order; the first aspect supplies its primary presentation language.
 */
public enum MagicAspect {
	FLAME,
	FROST,
	STORM,
	FORCE,
	MOTION,
	GRAVITY,
	TIME,
	SPACE,
	MIND,
	SOUL,
	LIFE,
	LIGHT,
	DARKNESS,
	VOID,
	PROTECTION,
	CONCEALMENT,
	CREATION,
	SUPPRESSION
}
